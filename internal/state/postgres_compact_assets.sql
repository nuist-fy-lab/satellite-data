-- Lossless PostgreSQL representation of the existing official_slots and
-- official_assets records. This is a shadow-schema migration component; the
-- running SQLite store is unchanged until reconciliation and cutover.
--
-- The key dictionary is a UNION of both logical relations. It preserves
-- orphan assets and slots independently; either relation may contain records
-- absent from the other in a historical snapshot.
CREATE TABLE IF NOT EXISTS pg_official_granule_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_key TEXT NOT NULL,
  slot_ts TEXT NOT NULL,
  granule_id TEXT NOT NULL,
  UNIQUE (product_key, slot_ts, granule_id)
);

-- Preserves product/day access with a small index: one tuple per granule,
-- rather than one tuple per asset.
CREATE INDEX IF NOT EXISTS pg_official_granule_day_idx
  ON pg_official_granule_keys (product_key, (substr(slot_ts, 1, 10)));

CREATE TABLE IF NOT EXISTS pg_official_slot_details (
  granule_key BIGINT PRIMARY KEY REFERENCES pg_official_granule_keys(id)
    ON DELETE CASCADE,
  asset_count BIGINT NOT NULL DEFAULT 0,
  total_size BIGINT NOT NULL DEFAULT 0,
  representative_filename TEXT NOT NULL DEFAULT '',
  refreshed_at TEXT NOT NULL
);

-- Split each URL at its final slash. Both pieces are stored byte-for-byte;
-- empty prefixes and URLs are supported. This is *lossless* dictionary
-- encoding, not a truncated URL or a provider-specific re-creation.
CREATE TABLE IF NOT EXISTS pg_official_url_prefixes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prefix TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS pg_official_asset_details (
  granule_key BIGINT NOT NULL REFERENCES pg_official_granule_keys(id)
    ON DELETE CASCADE,
  filename TEXT NOT NULL,
  url_prefix_id BIGINT REFERENCES pg_official_url_prefixes(id),
  -- NULL means the URL's final path component is exactly filename.
  -- Any other suffix, including the empty string, is stored verbatim.
  url_suffix TEXT,
  size BIGINT NOT NULL DEFAULT 0,
  etag TEXT NOT NULL DEFAULT '',
  media_type TEXT NOT NULL DEFAULT '',
  PRIMARY KEY(granule_key, filename)
);

-- PostgreSQL hash indexes are WAL-safe. They support exact equality lookups:
-- the executor rechecks full filename equality, so hash collisions cannot
-- lose or merge distinct files.
CREATE INDEX IF NOT EXISTS pg_official_asset_filename_idx
  ON pg_official_asset_details USING HASH (filename);

-- The original logical schema is exposed, including all fields and all rows.
CREATE OR REPLACE VIEW official_slots AS
SELECT k.product_key, k.slot_ts, k.granule_id,
       s.asset_count, s.total_size, s.representative_filename, s.refreshed_at
FROM pg_official_slot_details s
JOIN pg_official_granule_keys k ON k.id = s.granule_key;

CREATE OR REPLACE VIEW official_assets AS
SELECT k.product_key, k.slot_ts, k.granule_id, a.filename,
       (COALESCE(p.prefix, '') || COALESCE(a.url_suffix, a.filename)) AS url,
       a.size, a.etag, a.media_type
FROM pg_official_asset_details a
JOIN pg_official_granule_keys k ON k.id = a.granule_key
LEFT JOIN pg_official_url_prefixes p ON p.id = a.url_prefix_id;
